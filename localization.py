
def localize_issues(data, predictions, label_columns):
    """
    Match model predictions to dataset statements and report
    the source locations where issues were detected.

    Args:
        data: Dataset containing statement_id, code, and line_no.
        predictions: Predictions generated by the trained model.
        label_columns: Names of the predicted issue labels.

    Returns:
        A list of localized issue dictionaries.
    """

    localized_issues = []

    for index, prediction in enumerate(predictions):
        statement = data.iloc[index]
        code = str(statement["code"]).strip()

        detected_issues = []

        for i, label in enumerate(label_columns):
            if prediction[i] != 1:
                continue

            # Avoid treating a complete control-flow block
            # as a single long expression.
            if label == "long_statement":
                control_keywords = (
                    "if ",
                    "elif ",
                    "else:",
                    "for ",
                    "while ",
                    "try:",
                    "except ",
                    "finally:",
                    "with ",
                    "async for "
                )

                if code.startswith(control_keywords):
                    continue

            detected_issues.append(label)

        if detected_issues:
            localized_issues.append({
                "statement_id": statement["statement_id"],
                "line_no": statement["line_no"],
                "code": statement["code"],
                "detected_issues": detected_issues
            })

    return localized_issues


if __name__ == "__main__":
    from train_model import (
        train_model,
        build_features,
        LABEL_COLUMNS
    )

    model, data, _, test = train_model()
    test_data = data[test].reset_index(drop=True)
    predictions = model.predict(build_features(test_data))

    results = localize_issues(test_data, predictions, LABEL_COLUMNS)

    for result in results:
        print("-" * 40)
        print("Statement ID:", result["statement_id"])
        print("Line:", result["line_no"])
        print("Code:", result["code"])
        print("Detected Issues:", result["detected_issues"])
